"""Catálogos declarados.

Cada entrada mapea un nombre lógico a:
- la ruta en disco bajo `catalogos_co/` (relativa al directorio configurado),
- la fuente para sincronizar (Socrata API, SISPRO ASPX o REPS export),
- una descripción breve y un tag de licencia.

Para añadir un catálogo nuevo: agregar una `CatalogSource` aquí y correr
    python -m sync_catalogos.sync --catalog <name>
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from .schema import SourceKind


@dataclass(frozen=True)
class CatalogSource:
    name: str
    kind: SourceKind
    output_path: Path                       # relativo al root de catálogos
    description: str
    license: str = ""
    schedule_hint: str = "monthly"          # weekly, monthly, quarterly, yearly
    notes: str = ""

    # robots.txt / TOS — exige flag --i-have-permission para correr
    requires_explicit_consent: bool = False
    consent_reason: str = ""

    # Socrata-specific
    socrata_dataset_id: str | None = None
    socrata_extra_query: str | None = None

    # SISPRO-specific
    sispro_code: str | None = None
    sispro_page_size: int = 2000

    # REPS-specific
    reps_endpoint: str = ""                 # archivo bajo /habilitacion/consultas/

